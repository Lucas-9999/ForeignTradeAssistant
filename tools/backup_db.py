"""
FTA 数据库快照备份工具 (VACUUM INTO) — 任何 Migration / Bulk 操作前必须运行.

VACUUM INTO 在 WAL 模式下读取一致快照, 不会影响正在运行的
FastAPI / Streamlit / 调度进程, 是生产库 83MB 的安全备份手段.

Usage:
    python tools/backup_db.py                     # 默认标签 pre_migration
    python tools/backup_db.py --label pre_v7       # 迁移前: pre_v7
    python tools/backup_db.py --check              # 备份后立即 integrity_check + 体积对比
    python tools/backup_db.py --keep 3             # 只保留最近 3 份 (默认 5)

备份位置: data/backups/fta.db.pre_<label>_YYYYMMDD_HHMMSS
"""

from __future__ import annotations

import argparse
import re
import sqlite3
import sys
from datetime import datetime
from pathlib import Path

# Windows 控制台默认 cp936, 中文输出会乱码 — 强制 UTF-8.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

import config  # noqa: E402

BACKUP_DIR = config.DATA_DIR / "backups"


def _snapshot_path(label: str) -> Path:
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_label = "".join(c if c.isalnum() or c in "-_" else "_" for c in label)
    return BACKUP_DIR / f"fta.db.pre_{safe_label}_{stamp}"


def _prune_old(keep: int) -> list[Path]:
    """删除最旧的快照, 只保留最近 `keep` 份 (含本次). 幂等."""
    if keep <= 0:
        return []
    # Labels are operator-provided and vary (for example pre_v12 / pre_p13),
    # so filename alphabetical order does not represent backup age.  Every
    # snapshot generated by _snapshot_path ends in YYYYMMDD_HHMMSS.
    snaps = sorted(BACKUP_DIR.glob("fta.db.pre_*"), key=_snapshot_age_key)
    to_delete = snaps[:-keep]
    for p in to_delete:
        try:
            p.unlink()
            print(f"[pruned] {p.name}")
        except OSError as e:
            print(f"[warn] 无法删除 {p.name}: {e}", file=sys.stderr)
    return to_delete


def _snapshot_age_key(path: Path) -> tuple[int, str]:
    """Sort generated snapshots chronologically; malformed legacy names prune first."""
    match = re.search(r"_(\d{8}_\d{6})$", path.name)
    if match:
        return 1, match.group(1)
    # A malformed name must not displace a verified timestamped snapshot.
    return 0, f"{path.stat().st_mtime:020.6f}"


def _integrity(db_path: Path) -> str:
    """只读: PRAGMA integrity_check, 返回 'ok' 或错误文本."""
    try:
        con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        try:
            row = con.execute("PRAGMA integrity_check").fetchone()
            return row[0] if row else "ok"
        finally:
            con.close()
    except sqlite3.Error as e:
        return f"ERROR: {e}"


def main() -> int:
    ap = argparse.ArgumentParser(description="FTA 数据库快照备份 (VACUUM INTO)")
    ap.add_argument("--label", default="pre_migration",
                    help="快照标签, 如 pre_v7 / pre_bulk_import (默认 pre_migration)")
    ap.add_argument("--keep", type=int, default=5, help="保留最近 N 份, 默认 5")
    ap.add_argument("--check", action="store_true",
                    help="备份后运行 integrity_check 并与 live 库对比体积")
    args = ap.parse_args()

    if not config.DB_PATH.exists():
        print(f"[error] 找不到数据库: {config.DB_PATH}", file=sys.stderr)
        return 1

    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    dest = _snapshot_path(args.label)

    try:
        con = sqlite3.connect(str(config.DB_PATH))
        try:
            con.execute("VACUUM INTO ?", (str(dest),))
        finally:
            con.close()
    except sqlite3.Error as e:
        print(f"[error] VACUUM INTO 失败: {e}", file=sys.stderr)
        return 1

    live_size = config.DB_PATH.stat().st_size
    snap_size = dest.stat().st_size
    print(f"[ok] 已备份 -> {dest}")
    print(f"      live={live_size / 1e6:.1f}MB  snapshot={snap_size / 1e6:.1f}MB")

    _prune_old(args.keep)

    if args.check:
        result = _integrity(dest)
        ok = result == "ok"
        # VACUUM 会压实历史 UPDATE/DELETE 留下的空闲页, 快照通常比 live 小
        # 5–30%. 仅当明显更小(疑似截断)或明显更大(疑似 WAL 异常合并)才告警.
        lo, hi = 0.70, 1.10
        ratio = snap_size / live_size if live_size else 0.0
        sane = lo <= ratio <= hi
        print(f"      integrity_check: {result}")
        if ok:
            print(f"      体积对比: snapshot/live = {ratio:.1%} "
                  f"({'OK' if sane else 'WARN'})")
            if not sane:
                print("      [warn] 快照体积异常 (VACUUM 应压实至 70–110%), "
                      "建议检查 WAL/错误日志", file=sys.stderr)
        else:
            print(f"      [error] 快照损坏: {result}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
